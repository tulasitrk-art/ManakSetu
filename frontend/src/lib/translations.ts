/**
 * Main translation helper function
 */
export function getTranslation(lang: string, key: string, fallback?: string): string {
  const langDict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
  if (langDict && langDict[key]) {
    return langDict[key];
  }
  // Fallback to English dictionary
  if (UI_TRANSLATIONS.en && UI_TRANSLATIONS.en[key]) {
    return UI_TRANSLATIONS.en[key];
  }
  return fallback || key;
}

/**
 * Domain term translation helper
 */
export function translateDomainTerm(lang: string, term: string): string {
  if (!term || lang === "en") return term;
  if (DOMAIN_TERMS[term] && DOMAIN_TERMS[term][lang]) {
    return DOMAIN_TERMS[term][lang];
  }
  return term;
}
